const dictionaries: Record<Locale, Record<StringKey, string>> = { en, ja, 'zh-Hant': zhHant };

export const locales: { code: Locale; label: string }[] = [
  { code: 'en', label: 'English' },
  { code: 'ja', label: '日本語' },
  { code: 'zh-Hant', label: '繁體中文' },
];

/** Translate a key; `{{name}}` placeholders are replaced from `vars`. */
export function t(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[locale][key];
  for (const [name, value] of Object.entries(vars ?? {})) text = text.replaceAll(`{{${name}}}`, String(value));
  return text;
}

const intlLocale = (locale: Locale) => (locale === 'zh-Hant' ? 'zh-TW' : locale);

export const formatNumber = (locale: Locale, value: number) => new Intl.NumberFormat(intlLocale(locale)).format(value);

export const formatDateTime = (locale: Locale, iso: string) =>
  new Intl.DateTimeFormat(intlLocale(locale), { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(new Date(iso));

export const formatPercent = (locale: Locale, value: number) =>
  new Intl.NumberFormat(intlLocale(locale), { style: 'percent', maximumFractionDigits: 0, signDisplay: 'exceptZero' }).format(value);
